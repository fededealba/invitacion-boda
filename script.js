function changeLanguage(lang) {
    localStorage.setItem('wedding-lang', lang);

    // Update document language attribute
    document.documentElement.lang = lang;

    // Update text content
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });

    // Update active state of buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('onclick').includes(lang));
    });
}

// Scroll-triggered animations
function handleScrollAnimations(prefersReducedMotion) {
    if (prefersReducedMotion) {
        document.querySelectorAll('section, .timeline-item, .location-card, .detail-card').forEach(element => {
            element.classList.add('visible');
        });
        return;
    }

    const sections = document.querySelectorAll('section');
    const timelineItems = document.querySelectorAll('.timeline-item');
    const locationCards = document.querySelectorAll('.location-card');
    const detailCards = document.querySelectorAll('.detail-card');

    const observerOptions = {
        threshold: 0.15,
        rootMargin: '0px 0px -100px 0px'
    };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
            }
        });
    }, observerOptions);

    // Observe all sections
    sections.forEach(section => {
        observer.observe(section);
    });

    // Observe timeline items with staggered delay
    timelineItems.forEach((item, index) => {
        item.style.transitionDelay = `${index * 0.2}s`;
        observer.observe(item);
    });

    // Observe location cards with staggered delay
    locationCards.forEach((card, index) => {
        card.style.transitionDelay = `${index * 0.15}s`;
        observer.observe(card);
    });

    // Observe detail cards with staggered delay
    detailCards.forEach((card, index) => {
        card.style.transitionDelay = `${index * 0.1}s`;
        observer.observe(card);
    });
}

// Smooth scrolling for anchor links (if needed)
function initSmoothScroll() {
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                target.scrollIntoView({
                    behavior: 'smooth',
                    block: 'start'
                });
            }
        });
    });
}

// Initialize everything
document.addEventListener('DOMContentLoaded', () => {
    const prefersReducedMotion = window.matchMedia &&
        window.matchMedia('(prefers-reduced-motion: reduce)').matches;

    // Initialize language
    const savedLang = localStorage.getItem('wedding-lang') || 'es';
    changeLanguage(savedLang);

    // Initialize scroll animations
    handleScrollAnimations(prefersReducedMotion);

    // Initialize smooth scroll
    initSmoothScroll();

    // Mobile navigation toggle
    const topNav = document.querySelector('.top-nav');
    const navToggle = document.querySelector('.nav-toggle');
    const smallScreenQuery = window.matchMedia
        ? window.matchMedia('(max-width: 768px)')
        : null;

    const updateNavForViewport = () => {
        if (!topNav || !navToggle || !smallScreenQuery) return;

        if (smallScreenQuery.matches) {
            topNav.classList.remove('is-open');
            navToggle.setAttribute('aria-hidden', 'false');
            navToggle.setAttribute('aria-expanded', 'false');
        } else {
            // Always show nav on larger screens
            topNav.classList.add('is-open');
            navToggle.setAttribute('aria-hidden', 'true');
            navToggle.setAttribute('aria-expanded', 'true');
        }
    };

    if (topNav && navToggle && smallScreenQuery) {
        updateNavForViewport();
        smallScreenQuery.addEventListener('change', updateNavForViewport);

        navToggle.addEventListener('click', () => {
            const isOpen = topNav.classList.toggle('is-open');
            navToggle.setAttribute('aria-expanded', String(isOpen));
        });

        topNav.querySelectorAll('.nav-item').forEach(link => {
            link.addEventListener('click', () => {
                if (smallScreenQuery.matches) {
                    topNav.classList.remove('is-open');
                    navToggle.setAttribute('aria-expanded', 'false');
                }
            });
        });
    }

    // Make hero section visible immediately
    const heroSection = document.querySelector('#hero');
    if (heroSection) {
        heroSection.classList.add('visible');
    }
});

// Optional: Add parallax effect to hero section
(() => {
    const supportsMatchMedia = typeof window.matchMedia === 'function';
    const prefersReducedMotion = supportsMatchMedia &&
        window.matchMedia('(prefers-reduced-motion: reduce)').matches;

    if (prefersReducedMotion) {
        return;
    }

    window.addEventListener('scroll', () => {
        const scrolled = window.pageYOffset;
        const hero = document.querySelector('#hero');
        if (hero && scrolled < window.innerHeight) {
            hero.style.transform = `translateY(${scrolled * 0.5}px)`;
            hero.style.opacity = 1 - (scrolled / window.innerHeight) * 0.8;
        }
    });
})();
